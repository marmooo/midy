/** Embed synth_core.wasm variants as base64 into src/. */

async function embed(
  wasmUrl: URL,
  outUrl: URL,
  exportName: string,
  label: string,
  required: boolean,
): Promise<void> {
  let bytes: Uint8Array;
  try {
    bytes = await Deno.readFile(wasmUrl);
  } catch {
    if (required) {
      console.error(`Missing ${wasmUrl.pathname} — run: bash wasm/build.sh`);
      Deno.exit(1);
    }
    console.warn(`skip ${label} embed (no ${wasmUrl.pathname})`);
    return;
  }
  let binary = "";
  const chunk = 0x8000;
  for (let i = 0; i < bytes.length; i += chunk) {
    binary += String.fromCharCode(...bytes.subarray(i, i + chunk));
  }
  const b64 = btoa(binary);
  const src =
    `// Auto-generated by wasm/scripts/embed_wasm.ts (${bytes.length} bytes, ${label})\n` +
    `// Do not edit by hand. Rebuild: deno task build:wasm-core\n` +
    `export const ${exportName} =\n  "${b64}";\n`;
  await Deno.mkdir(new URL(".", outUrl), { recursive: true });
  await Deno.writeTextFile(outUrl, src);
  console.log(`wrote ${outUrl.pathname} (${bytes.length} bytes, ${label})`);
}

await embed(
  new URL("../dist/synth_core.wasm", import.meta.url),
  new URL("../../src/synth_core_wasm_b64.ts", import.meta.url),
  "SYNTH_CORE_WASM_BASE64",
  "scalar",
  true,
);
