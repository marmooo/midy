/** Embed dist/synth_core.wasm as base64 into src/synth_core_wasm_b64.ts
 *
 * Paths (when this package lives at midy repo root):
 *   wasm/scripts/embed_wasm.ts  →  ../../src/synth_core_wasm_b64.ts
 */
const wasmPath = new URL("../dist/synth_core.wasm", import.meta.url);

let bytes: Uint8Array;
try {
  bytes = await Deno.readFile(wasmPath);
} catch {
  console.error("Missing dist/synth_core.wasm — run: bash build.sh  (needs wasm-ld)");
  Deno.exit(1);
}

let binary = "";
const chunk = 0x8000;
for (let i = 0; i < bytes.length; i += chunk) {
  binary += String.fromCharCode(...bytes.subarray(i, i + chunk));
}
const b64 = btoa(binary);

const src =
  `// Auto-generated by wasm/scripts/embed_wasm.ts (${bytes.length} bytes)\n` +
  `// Do not edit by hand. Rebuild: deno task build:wasm-core\n` +
  `export const SYNTH_CORE_WASM_BASE64 =\n  "${b64}";\n`;

const outPath = new URL("../../src/synth_core_wasm_b64.ts", import.meta.url);

await Deno.mkdir(new URL(".", outPath), { recursive: true });
await Deno.writeTextFile(outPath, src);
console.log(`wrote ${outPath.pathname} (${bytes.length} wasm bytes)`);
